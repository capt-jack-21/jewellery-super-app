// Build-time: derive the API version from contracts/openapi.yaml info.version (single source; never hand-edit the output).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const yaml = readFileSync(join(root, 'contracts/openapi.yaml'), 'utf8');
const info = yaml.split(/\r?\n/).slice(yaml.split(/\r?\n/).indexOf('info:') + 1);
const line = info.find((l) => /^ {2}version:\s*/.test(l));
const version = line?.replace(/^ {2}version:\s*/, '').replace(/['"]/g, '').trim();
if (!version || !/^\d+\.\d+\.\d+([-+].+)?$/.test(version)) { console.error('gen-contract-version: info.version not found'); process.exit(1); }
const out = join(root, 'packages/modules/platform/src/internal/contract-version.ts');
const src = `// GENERATED by scripts/gen-contract-version.mjs from contracts/openapi.yaml info.version — do not edit.\nexport const CONTRACT_VERSION = '${version}';\n`;
let cur = ''; try { cur = readFileSync(out, 'utf8'); } catch { /* first run */ }
if (cur !== src) writeFileSync(out, src);
